import { describe, expect, it } from 'vitest';
import {
  MODEL_ASSET_SCHEMA_VERSION,
  MODEL_IMPORT_BUDGET,
  resolveSemanticClip,
  validateModelAssetRecord,
  type ModelAssetRecord,
} from './contracts.js';

const validRecord: ModelAssetRecord = {
  schemaVersion: MODEL_ASSET_SCHEMA_VERSION,
  id: 'phase5-rig-fixture',
  runtimePath: 'models/phase5-rig-fixture.glb',
  runtimeFormat: 'glb',
  sourceFormat: 'procedural-glb',
  sourceOrigin: 'Generated by the checked-in Phase 5 fixture builder.',
  sourceSha256: 'a'.repeat(64),
  outputSha256: 'b'.repeat(64),
  importer: 'phase5-fixture-builder',
  importerVersion: '1',
  conversionOptions: {
    outputFormat: 'glb',
    preserveSkinning: true,
    preserveMorphTargets: true,
    preserveAnimations: true,
  },
  rights: {
    licenseId: 'CC0-1.0',
    attribution: '',
    commercialUse: true,
    redistribution: true,
    approved: true,
  },
  normalization: {
    metersPerUnit: 1,
    sourceUpAxis: 'Y',
    sourceForwardAxis: '-Z',
    upAxis: 'Y',
    forwardAxis: '-Z',
    rootRotation: [0, 0, 0, 1],
  },
  bounds: { min: [-0.5, 0, -0.2], max: [0.5, 2, 0.2] },
  metrics: {
    sourceBytes: 4096,
    outputBytes: 4096,
    triangles: 120,
    primitiveCount: 1,
    textureCount: 1,
    textureBytes: 2048,
    maxTextureDimension: 8,
    jointCount: 2,
    skinCount: 1,
    morphTargetNames: [],
    estimatedDecodedBytes: 4096,
  },
  extensions: [],
  materialNames: ['Fixture material'],
  clipInventory: [
    { name: 'Idle', durationSeconds: 1 },
    { name: 'Walk', durationSeconds: 1 },
    { name: 'Wave', durationSeconds: 0.8 },
  ],
  clips: { idle: 'Idle', move: 'Walk', interact: 'Wave' },
  fallbackAction: 'idle',
  warnings: [],
};

describe('model asset contracts', () => {
  it('accepts an approved local GLB record with complete provenance', () => {
    expect(validateModelAssetRecord(validRecord)).toEqual([]);
  });

  it('rejects JSON glTF as a runtime asset because referenced files cannot be lease-verified', () => {
    const invalid = {
      ...validRecord,
      runtimePath: 'models/phase5-rig-fixture.gltf',
      runtimeFormat: 'gltf',
    };
    const paths = validateModelAssetRecord(invalid).map((diagnostic) => diagnostic.path);
    expect(paths).toContain('runtimePath');
    expect(paths).toContain('runtimeFormat');
  });

  it('rejects traversal, malformed hashes, unapproved rights, and out-of-budget records', () => {
    const invalid = {
      ...validRecord,
      runtimePath: 'models/../private.glb',
      outputSha256: 'not-a-hash',
      metrics: { ...validRecord.metrics, triangles: MODEL_IMPORT_BUDGET.maxTriangles + 1 },
      rights: { ...validRecord.rights, approved: false },
    };
    const paths = validateModelAssetRecord(invalid).map((diagnostic) => diagnostic.path);
    expect(paths).toContain('runtimePath');
    expect(paths).toContain('outputSha256');
    expect(paths).toContain('metrics.triangles');
    expect(paths).toContain('rights.approved');
  });

  it('requires finite ordered bounds, a supported coordinate convention, and semantic clip names', () => {
    const invalid = {
      ...validRecord,
      bounds: { min: [2, 0, 0], max: [1, Number.NaN, 0] },
      normalization: { ...validRecord.normalization, metersPerUnit: 0 },
      clips: { walk: 'Walk' },
    };
    const paths = validateModelAssetRecord(invalid).map((diagnostic) => diagnostic.path);
    expect(paths).toContain('bounds');
    expect(paths).toContain('normalization.metersPerUnit');
    expect(paths).toContain('clips.walk');
  });

  it('uses an authored idle fallback for absent action clips', () => {
    expect(resolveSemanticClip(validRecord, 'combat')).toBe('Idle');
    expect(resolveSemanticClip({ clips: {}, fallbackAction: 'static' }, 'move')).toBeNull();
  });

  it('rejects records that would strip rig data, use invalid axis transforms, or map missing clips', () => {
    const invalid = {
      ...validRecord,
      conversionOptions: { ...validRecord.conversionOptions, preserveAnimations: false },
      normalization: { ...validRecord.normalization, rootRotation: [0, 0, 0, 0] },
      clips: { ...validRecord.clips, combat: 'Missing' },
      metrics: { ...validRecord.metrics, outputBytes: MODEL_IMPORT_BUDGET.maxFileBytes + 1 },
    };
    const paths = validateModelAssetRecord(invalid).map((diagnostic) => diagnostic.path);
    expect(paths).toContain('conversionOptions.preserveAnimations');
    expect(paths).toContain('normalization.rootRotation');
    expect(paths).toContain('clips.combat');
    expect(paths).toContain('metrics.outputBytes');
  });
});
